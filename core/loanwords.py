_KATA_INNER = r"ー\u30a1-\u30fa"
# 按长度降序，长词优先（アップデート 先于 アプデ 命中）
_PATTERNS = sorted(LOANWORDS.keys(), key=len, reverse=True)
_KATA_RUN = re.compile(r"[" + _KATA_INNER + r"]+")


def _replace_run(run: str) -> str:
    """对一段连续的片假名，按最长匹配贪心替换成中文（相邻的「ナイスショット」也能拆开）。"""
    out, i, n = [], 0, len(run)
    while i < n:
        hit = next((p for p in _PATTERNS if run.startswith(p, i)), None)
        if hit:
            out.append(LOANWORDS[hit])
            i += len(hit)
        else:
            out.append(run[i])
            i += 1
    return "".join(out)


def apply_loanwords(text: str) -> str:
    """把片假名外来语替换成中文。整段连续片假名内贪心最长匹配，避免子串/相邻词误伤。"""
    if not text:
        return text
    return _KATA_RUN.sub(lambda m: _replace_run(m.group(0)), text)


