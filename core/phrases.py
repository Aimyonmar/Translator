# 归一化时要去掉的东西：空格、标点、长音符、重复感叹
_SPACE = re.compile(r"[\s　]+")
_PUNCT = re.compile(r"[、。，,．\.！!？\?・…‥～~ー～\-—_『』「」（）()\[\]【】“”\"'’‘:：;；/\\]+")
_REPEAT = re.compile(r"(.)\1{1,}$")


def norm(text: str) -> str:
    """归一化：忽略空格/标点/长音符/片尾重复符号的差异。"""
    s = (text or "").strip()
    s = _SPACE.sub("", s)
    s = _PUNCT.sub("", s)
    s = s.replace("ー", "").replace("～", "").replace("~", "")
    # 全角英数转半角，方便 "OK" / "ＢＧＭ" 之类统一
    out = []
    for ch in s:
        code = ord(ch)
        if 0xFF01 <= code <= 0xFF5E:
            out.append(chr(code - 0xFEE0))
        else:
            out.append(ch)
    s = "".join(out)
    return s.lower()


