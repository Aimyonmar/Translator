# -*- coding: utf-8 -*-
"""音频转文字（离线文件转写）：把整段音频/视频转成带时间戳的文本，导出 TXT / SRT。

与实时字幕的区别：
- 输入是文件，不是系统声音回环；一次性转完，进度按「已转写时长 / 总时长」推进；
- 解码宽度用 5（离线更看重准确度，实时那套 beam=2 是为延迟服务的）；
- 打开 VAD 过滤，跳过整段静音，避免 Whisper 在长静音上循环吐幻觉句。
"""
from __future__ import annotations

import json
import os
from dataclasses import dataclass, field
from datetime import datetime
from typing import Callable, Dict, List, Optional, Tuple

import numpy as np

from .asr import _batch_supported

SAMPLE_RATE = 16000

# 句段：兼容旧的 (起始秒, 结束秒, 文本) 元组（实时记录导出仍在用）
Segment = Tuple[float, float, str]

# 工程文件格式版本：字段一旦对外就不要再改含义，只能加字段
PROJECT_SCHEMA = "translator-project/1"


@dataclass
class Cue:
    """一句字幕。文件转写统一用它，实时记录导出仍可直接传三元组。"""
    start: float
    end: float
    text: str
    # 字词时间码：[{"s": 起, "e": 止, "t": 词, "p": 置信度}]，秒、三位小数
    words: List[Dict[str, float]] = field(default_factory=list)
    # 译文：离线翻译后回填，与 text 一一对应（可能为空）
    tgt: str = ""


def _span(seg) -> Tuple[float, float, str]:
    """统一取 (起, 止, 文本)，Cue 与三元组都能用。"""
    if isinstance(seg, Cue):
        return seg.start, seg.end, seg.text
    return float(seg[0]), float(seg[1]), seg[2]


def _tgt(seg) -> str:
    return seg.tgt if isinstance(seg, Cue) else ""


# faster-whisper 走 PyAV/ffmpeg 解码，下面这些容器/编码都能直接读
AUDIO_EXTS = (
    ".wav", ".mp3", ".m4a", ".aac", ".flac", ".ogg", ".opus", ".wma",
    ".mp4", ".mkv", ".mov", ".webm", ".avi", ".ts", ".flv",
)
FILE_FILTER = ("音频/视频 (" + " ".join("*" + e for e in AUDIO_EXTS) + ");;"
               "所有文件 (*.*)")


def format_ts(seconds: float, sep: str = ".") -> str:
    """秒 → HH:MM:SS.mmm（SRT 用 sep=","）。"""
    seconds = max(0.0, float(seconds))
    ms = int(round(seconds * 1000.0))
    h, ms = divmod(ms, 3600_000)
    m, ms = divmod(ms, 60_000)
    s, ms = divmod(ms, 1000)
    return f"{h:02d}:{m:02d}:{s:02d}{sep}{ms:03d}"


def to_txt(segments: List[Segment]) -> str:
    """TXT：每行「[起 → 止] 文本」，时间戳保留到毫秒，方便对照原片。"""
    out = []
    for seg in segments:
        a, b, t = _span(seg)
        out.append(f"[{format_ts(a)} → {format_ts(b)}] {t}\n")
        g = _tgt(seg)
        if g:
            out.append(f"    {g}\n")
    return "".join(out)


def to_srt(segments: List[Segment], bilingual: bool = False) -> str:
    """标准 SRT：序号 + 时间轴 + 文本，播放器/剪辑软件可直接载入。

    bilingual=True 时把译文接在原文下一行（同一句字幕内两行），
    这是非英语平台/剪辑软件最通用的双语做法。
    """
    out = []
    for i, seg in enumerate(segments, 1):
        a, b, t = _span(seg)
        g = _tgt(seg)
        body = f"{t}\n{g}" if (bilingual and g) else t
        out.append(f"{i}\n{format_ts(a, ',')} --> {format_ts(b, ',')}\n{body}\n")
    return "\n".join(out)


def to_translation_srt(segments: List[Segment]) -> str:
    """单独译文 SRT：只保留有译文的句子，时间码沿用原句，正文用译文。"""
    out = []
    for seg in segments:
        g = _tgt(seg)
        if g:
            a, b, _t = _span(seg)
            out.append(Cue(a, b, g))
    return to_srt(out)


def _ass_ts(seconds: float) -> str:
    """秒 → H:MM:SS.cc（ASS 只认两位厘秒）。"""
    cs = int(round(max(0.0, float(seconds)) * 100.0))
    h, cs = divmod(cs, 360_000)
    m, cs = divmod(cs, 6_000)
    s, cs = divmod(cs, 100)
    return f"{h:d}:{m:02d}:{s:02d}.{cs:02d}"


def _ass_text(text: str) -> str:
    """ASS 正文转义：换行用 \\N，花括号会被当成特效标签，换成全角。"""
    return (text.replace("\\", "＼").replace("{", "｛").replace("}", "｝")
                .replace("\r\n", "\n").replace("\n", "\\N"))


def to_ass(segments: List[Segment], title: str = "Translator",
           font: str = "Microsoft YaHei UI", font_size: int = 60,
           bilingual: bool = False) -> str:
    """基础 ASS：1920x1080、底部居中、白字黑边，可直接拖进 Aegisub / PR / 达芬奇。

    只保留「能播、能改样式」的最低限度字段；不做特效与逐字卡拉 OK（那是编辑器的事）。
    """
    head = (
        "[Script Info]\n"
        f"; Generated by Translator\n"
        f"Title: {title}\n"
        "ScriptType: v4.00+\n"
        "PlayResX: 1920\n"
        "PlayResY: 1080\n"
        "WrapStyle: 0\n"
        "ScaledBorderAndShadow: yes\n\n"
        "[V4+ Styles]\n"
        "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, "
        "OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, "
        "ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, "
        "MarginL, MarginR, MarginV, Encoding\n"
        f"Style: Default,{font},{int(font_size)},&H00FFFFFF,&H000000FF,&H00000000,"
        "&H64000000,0,0,0,0,100,100,0,0,1,3,1,2,80,80,60,1\n\n"
        "[Events]\n"
        "Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text\n"
    )
    lines = []
    for seg in segments:
        a, b, t = _span(seg)
        g = _tgt(seg)
        body = f"{t}\n{g}" if (bilingual and g) else t
        lines.append(
            f"Dialogue: 0,{_ass_ts(a)},{_ass_ts(b)},Default,,0,0,0,,{_ass_text(body)}\n")
    return head + "".join(lines)


def to_project_json(segments: List[Segment], media_path: str = "",
                    duration: float = 0.0, language: str = "", model: str = "",
                    device: str = "", beam_size: int = 0,
                    word_timestamps: bool = True) -> str:
    """工程 JSON：转写结果的完整落盘格式，供后续批量转写 / 校对 / 再导出直接读取。

    字段约定（只增不改）：
    - `schema`：格式版本，当前 `translator-project/1`；
    - `media`：源文件路径、文件名、时长、语种；
    - `asr`：模型/设备/解码宽度/是否带字词时间码（复现与对比用）；
    - `cues`：与 SRT 一一对应的句，`words` 挂在句上（无字词时间码时为空数组）。
    """
    cues = []
    for i, seg in enumerate(segments, 1):
        a, b, t = _span(seg)
        cues.append({
            "i": i,
            "start": round(a, 3),
            "end": round(b, 3),
            "text": t,
            "tgt": _tgt(seg),
            "words": list(seg.words) if isinstance(seg, Cue) else [],
        })
    data = {
        "schema": PROJECT_SCHEMA,
        "created": datetime.now().isoformat(timespec="seconds"),
        "media": {
            "path": media_path,
            "name": os.path.basename(media_path),
            "duration_s": round(float(duration), 3),
            "language": language,
        },
        "asr": {
            "model": model,
            "device": device,
            "beam_size": int(beam_size),
            "word_timestamps": bool(word_timestamps),
        },
        "cues": cues,
    }
    return json.dumps(data, ensure_ascii=False, indent=1)


# 断句优先在这些字符之后下刀（中日英标点）
_CUT_PUNCT = "、。，．！？!?,;；:：…"
# 没有标点时的次选：切在助词**前**，避免把词/短语从中间劈开
_CUT_PARTICLES = "はがをにでともへのや"


def _split_text(text: str, max_chars: int) -> List[str]:
    """把一句切成每段 ≤ max_chars，优先级：标点 > 空格 > 助词前 > 硬切。

    标点之后永远是最自然的边界，所以标点不设下限；只有退到空格/助词/硬切时
    才要求切点落在后半段（floor），否则会切出大量极短的碎片。
    """
    out: List[str] = []
    rest = (text or "").strip()
    floor = max(2, int(max_chars * 0.5))
    while len(rest) > max_chars:
        window = rest[:max_chars]
        cut = -1
        for i in range(len(window) - 1, 0, -1):
            if window[i] in _CUT_PUNCT:
                cut = i + 1
                break
        if cut < 0:
            for i in range(len(window) - 1, floor - 1, -1):
                if window[i] == " ":
                    cut = i + 1
                    break
        if cut < 0:
            for i in range(len(window) - 1, floor - 1, -1):
                if window[i] in _CUT_PARTICLES:
                    cut = i          # 助词留在下一段开头
                    break
        if cut <= 0:
            cut = max_chars
        piece = rest[:cut].strip()
        if piece:
            out.append(piece)
        rest = rest[cut:].strip()
    if rest:
        out.append(rest)
    return out


def _time_at(offset: int, words: List[dict], start: float, end: float,
             total_chars: int) -> float:
    """把「第几个字符」映射成时间：有字词时间码按词内线性插值，否则按字数比例。"""
    if not words:
        return start + (end - start) * (offset / max(1, total_chars))
    cum = 0
    for w in words:
        n = len(str(w.get("t", "")).strip())
        if n <= 0:
            continue
        prev, cum = cum, cum + n
        if offset <= cum:
            ws = float(w.get("s", start))
            we = float(w.get("e", end))
            if offset <= prev:
                return ws
            return ws + (we - ws) * ((offset - prev) / n)
    return end


def resplit(segments: List[Segment], max_chars: int) -> List[Cue]:
    """按最大字数重新断句，返回新的 Cue 列表（不改动传入对象）。

    时间分配方式：
    1. 句内**有字词时间码**时，切点落在词边界，词内按字符位置线性插值，
       并把落在该段的字词时间码一起搬过去（工程 JSON 仍可精修）；
    2. **没有**字词时间码时，按各段字数比例均分整句时长。
    两种情况都保证时间码单调、不重叠、不超出原句范围。
    """
    if not max_chars or max_chars <= 0:
        return list(segments)
    out: List[Cue] = []
    for seg in segments:
        a, b, t = _span(seg)
        words = list(seg.words) if isinstance(seg, Cue) else []
        tgt = _tgt(seg)
        chunks = _split_text(t, max_chars)
        if len(chunks) <= 1:
            out.append(Cue(a, b, t, words, tgt))
            continue
        total_chars = max(1, sum(len(c) for c in chunks))
        # 字词的字符区间，用来把每个词分给对应的那一段
        word_spans: List[Tuple[int, int, dict]] = []
        cum = 0
        for w in words:
            n = len(str(w.get("t", "")).strip())
            if n > 0:
                word_spans.append((cum, cum + n, w))
                cum += n
        prev_t, char_pos = a, 0
        for i, c in enumerate(chunks):
            c0, char_pos = char_pos, char_pos + len(c)
            t_end = b if i == len(chunks) - 1 else _time_at(char_pos, words, a, b, total_chars)
            if t_end <= prev_t:
                t_end = min(b, prev_t + 0.01)
            part = [w for ws, we, w in word_spans if c0 <= (ws + we) / 2 < char_pos]
            out.append(Cue(prev_t, t_end, c, part, ""))
            prev_t = t_end
        # 译文无法安全切分：挂在最后一段，避免前半句被误认为已有完整译文
        if tgt:
            out[-1].tgt = tgt
    return out


def translate_segments(translator, segments: List[Segment], roster: str = "",
                       builtin_titles: bool = True,
                       on_progress: Optional[Callable[[int, int], None]] = None,
                       should_stop: Optional[Callable[[], bool]] = None) -> int:
    """逐句翻译并回填 `Cue.tgt`，返回成功的句数。

    完全复用 `Translator.translate()`：通道顺序、主备补发、译文缓存、本地口语表、
    日语归一 / 外来语替换 / 中文润色都在里面，这里不重复实现。
    标题术语替换与实时链路保持一致（机翻不认识游戏名）。
    """
    total = len(segments)
    done = 0
    for i, seg in enumerate(segments, 1):
        if should_stop is not None and should_stop():
            break
        src = _span(seg)[2]
        if not src:
            continue
        send = src
        if roster or builtin_titles:
            try:
                from .namefix import apply_title_glossary
                send = apply_title_glossary(src, roster, builtin=builtin_titles)
            except Exception:
                send = src
        try:
            out = translator.translate(send)
        except Exception:
            out = None
        if out:
            if isinstance(seg, Cue):
                seg.tgt = out
            done += 1
        if on_progress is not None:
            on_progress(i, total)
    return done


def decode_audio(path: str, sampling_rate: int = SAMPLE_RATE,
                 should_stop: Optional[Callable[[], bool]] = None) -> np.ndarray:
    """把任意音视频文件解成单声道 16k float32 PCM。

    `should_stop` 用于取消：长视频解码要几十秒，逐帧检查，命中就立刻返回空数组
    （否则点了取消还要等整段解完才停，界面看起来像卡死）。

    不复用 faster-whisper 自带的 decode_audio：它给 `av.open` 传了
    metadata_errors="ignore"，而 PyAV 19 已经删掉这个参数（实时字幕只喂内存
    数组，从不走文件解码，所以这个问题一直没暴露）。这里统一解成数组再交给
    Whisper，PyAV 新旧版本都能跑。
    """
    import av

    resampler = av.AudioResampler(format="s16", layout="mono", rate=sampling_rate)
    chunks: List[np.ndarray] = []

    def _take(out) -> None:
        if out is None:
            return
        if isinstance(out, (list, tuple)):
            for frame in out:
                _take(frame)
            return
        arr = out.to_ndarray()
        if arr.ndim > 1:
            arr = arr[0]
        chunks.append(arr)

    with av.open(path) as container:
        if not container.streams.audio:
            raise RuntimeError("这个文件里没有音轨")
        stream = container.streams.audio[0]
        stream.thread_type = "AUTO"
        for frame in container.decode(stream):
            if should_stop is not None and should_stop():
                return np.zeros(0, dtype=np.float32)
            _take(resampler.resample(frame))
        _take(resampler.resample(None))     # 冲掉重采样器里剩下的尾巴

    if not chunks:
        return np.zeros(0, dtype=np.float32)
    return np.concatenate(chunks).astype(np.float32) / 32768.0


def _apply_fixes(text: str, word_map: str, roster: str) -> str:
    """和实时字幕用同一套确定性修正（纠错表 + 音近人名），保证两条路径出来的名字一致。"""
    from .asr import WhisperASR
    if word_map:
        text = WhisperASR.apply_word_map(text, word_map)
    if roster:
        from .namefix import apply_names
        text = apply_names(text, roster)
    return text


def _words_supported(model) -> bool:
    """老版本 faster-whisper 的 transcribe 没有 word_timestamps 参数。"""
    try:
        import inspect
        return "word_timestamps" in inspect.signature(model.transcribe).parameters
    except Exception:
        return False


def transcribe_media(asr, path: str, language: Optional[str] = "ja",
                     word_map: str = "", roster: str = "",
                     word_timestamps: bool = True,
                     on_progress: Optional[Callable[[int], None]] = None,
                     should_stop: Optional[Callable[[], bool]] = None
                     ) -> Tuple[List[Cue], float]:
    """转写一个音视频文件，返回 (Cue 列表, 总时长秒)。

    复用已经加载好的实时模型（asr.model），不另起一份 —— 两份模型同时驻留显存
    正是「与实时字幕互斥」要避免的情况。调用方负责保证模型已 load。
    `word_timestamps=True` 时每句额外带上字词时间码（供工程 JSON 与重新断句用）。
    """
    if asr.model is None:
        raise RuntimeError("模型尚未加载")
    if not os.path.isfile(path):
        raise FileNotFoundError(path)

    kwargs = dict(
        language=language,
        beam_size=5,                    # 离线不吃延迟，用更宽的解码换准确度
        vad_filter=True,                # 长静音/纯 BGM 段落跳过，避免循环幻觉
        condition_on_previous_text=False,
        temperature=[0.0, 0.4, 0.6],
    )
    if _batch_supported() and getattr(asr, "batch_size", 1) > 1:
        kwargs["batch_size"] = asr.batch_size
    want_words = bool(word_timestamps) and _words_supported(asr.model)
    if want_words:
        kwargs["word_timestamps"] = True

    if should_stop is not None and should_stop():
        return [], 0.0
    audio = decode_audio(path, should_stop=should_stop)
    # 解码被取消：直接返回空结果，别把「解出 0 字节」误报成文件损坏
    if should_stop is not None and should_stop():
        return [], 0.0
    if audio.size == 0:
        raise RuntimeError("没有解出音频内容，确认文件没损坏、也不是纯图片/纯文本")

    segments: List[Cue] = []
    total = 0.0
    with asr.lock:                      # 与实时识别共用同一份模型，串行使用
        seg_iter, info = asr.model.transcribe(audio, **kwargs)
        total = float(getattr(info, "duration", 0.0) or 0.0)
        for seg in seg_iter:
            if should_stop is not None and should_stop():
                break
            text = (seg.text or "").strip()

            if text:
                text = _apply_fixes(text, word_map, roster)
                words = []
                if want_words:
                    for w in (getattr(seg, "words", None) or []):
                        wt = (getattr(w, "word", "") or "").strip()
                        if wt:
                            words.append({
                                "s": round(float(w.start), 3),
                                "e": round(float(w.end), 3),
                                "t": wt,
                                "p": round(float(getattr(w, "probability", 0.0) or 0.0), 3),
                            })
                segments.append(Cue(float(seg.start), float(seg.end), text, words))
            if on_progress is not None and total > 0:
                # 留 1% 给收尾（写文件、刷新界面），别让进度条卡在 100% 等
                on_progress(min(99, int(float(seg.end) / total * 100)))
    if on_progress is not None:
        on_progress(100)
    return segments, total
